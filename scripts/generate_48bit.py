"""Generate RV32/RV64 ETISS plugins with the experimental 48-bit K encodings."""

import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]


def generate(root, m2isar, work, xlen):
    work.mkdir(parents=True, exist_ok=False)
    cdsl = root / "etiss_arch_riscv"
    extension = root / "riscv-48bit-flow" / "cdsl" / "RVK.core_desc"
    # Use the maintained ETISS support descriptions and their own pinned rv_base.
    # Only the experimental instruction definitions come from the reference flow.
    rvk = extension.read_text().replace(
        '"rv_base/RVI.core_desc"', json.dumps(str(cdsl / "rv_base/RVI.core_desc"))
    )
    # Explicit modular register write: accepted by the strict source validator
    # for both XLENs, with the same semantics as the reference's implicit cast.
    assignment = "X[rd % RFS] = X[rs1 % RFS] + (signed)imm;"
    if rvk.count(assignment) != 1:
        raise ValueError("48-bit K_ADDI source changed; review the conversion overlay")
    rvk = rvk.replace(assignment, "X[rd % RFS] = (unsigned<XLEN>)(X[rs1 % RFS] + (signed)imm);")
    (work / "RVK.core_desc").write_text(rvk)
    top_file = cdsl / "top.core_desc"
    top = re.sub(r'import "([^"\n]+)"',
                 lambda m: "import " + json.dumps(str(cdsl / m[1])), top_file.read_text())
    top = 'import "RVK.core_desc"\n' + top
    for bits in (32, 64):
        top = top.replace(f"Core RV{bits}IMACFD ", f"Core RV{bits}IMACFDK ")
    top = top.replace("tum_semihosting {", "tum_semihosting, RV32K {")
    (work / "top.core_desc").write_text(top)
    env = dict(os.environ, PYTHONPATH=str(m2isar))
    subprocess.run([sys.executable, "-m", "m2isar.frontends.coredsl2.parser",
                    str(work / "top.core_desc"), "--infer-types", "--validate"],
                   env=env, check=True)
    subprocess.run([sys.executable, "-m", "m2isar.backends.etiss.writer",
                    str(work / "gen_model/top.m2isarmodel"), "--separate",
                    "--static-scalars", "--coverage", "--fill-mode", "auto"],
                   env=env, check=True)
    arch = f"RV{xlen}IMACFDK"
    output = work / "output" / arch
    shutil.copytree(work / "gen_output/top" / arch, output)
    # Wider instruction words are required in the simulator as well as the
    # plugin; fail compilation rather than silently truncating 48-bit opcodes.
    arch_source = output / (arch + "Arch.cpp")
    arch_source.write_text(arch_source.read_text() + '\n#include "etiss/Instruction.h"\n'
                           'static_assert(sizeof(etiss::instr::I) >= 6, '
                           '"ETISS requires upstream 48-bit fetch support (64-bit instruction word)");\n')
    for path in output.iterdir():
        if path.suffix in {".h", ".c", ".cpp", ".txt"}:
            path.write_text(re.sub(r"(?m)^([ #*]+)Generated on .*\.$",
                                  r"\1Generated by M2-ISA-R; see generation.json.", path.read_text()))
    refs = {"architecture": arch, "fill_mode": "auto",
            "top_sha256": hashlib.sha256(top_file.read_bytes()).hexdigest(),
            "rvk_sha256": hashlib.sha256(extension.read_bytes()).hexdigest(),
            "k_addi_explicit_cast": True, "etiss_instruction_word_bits": 64}
    for name, repo in (("rv_48bit", root / "riscv-48bit-flow"),
                       ("cdsl", cdsl), ("rv_base", cdsl / "rv_base"),
                       ("m2isar", m2isar), ("etiss", root / "etiss")):
        refs[name] = subprocess.check_output(["git", "-C", str(repo), "rev-parse", "HEAD"], text=True).strip()
    (output / "generation.json").write_text(json.dumps(refs, indent=2, sort_keys=True) + "\n")
    print(output)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--xlen", type=int, choices=(32, 64), required=True)
    parser.add_argument("--m2isar", type=Path, default=ROOT / "M2-ISA-R")
    parser.add_argument("--work", type=Path, required=True)
    args = parser.parse_args()
    generate(ROOT, args.m2isar.resolve(), args.work.resolve(), args.xlen)
