"""Record the source revisions used to generate a default ETISS architecture."""

import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess


def record(root, architecture, top, fill_mode, gdb_xml_descr):
    directory = root / "etiss" / "ArchImpl" / architecture
    top_file = root / "etiss_arch_riscv" / (top + ".core_desc")
    refs = {
        "architecture": architecture,
        "top_sha256": hashlib.sha256(top_file.read_bytes()).hexdigest(),
        "fill_mode": fill_mode,
        "gdb_xml_descr": gdb_xml_descr,
    }
    for name, repo in (
        ("cdsl", root / "etiss_arch_riscv"),
        ("rv_base", root / "etiss_arch_riscv" / "rv_base"),
        ("m2isar", root / "M2-ISA-R"),
        ("etiss", root / "etiss"),
    ):
        refs[name] = subprocess.check_output(
            ["git", "-C", str(repo), "rev-parse", "HEAD"], text=True
        ).strip()
    for path in directory.iterdir():
        if path.suffix in {".h", ".c", ".cpp", ".txt"}:
            source = path.read_text()
            source = re.sub(
                r"(?m)^([ #*]+)Generated on .*\.$",
                r"\1Generated by M2-ISA-R; see generation.json.",
                source,
            )
            path.write_text(source)
    (directory / "generation.json").write_text(
        json.dumps(refs, indent=2, sort_keys=True) + "\n"
    )


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("architecture")
    parser.add_argument("--top", default="top")
    parser.add_argument("--fill-mode", required=True)
    parser.add_argument("--gdb-xml-descr", required=True)
    args = parser.parse_args()
    record(Path(__file__).resolve().parents[1], args.architecture, args.top,
           args.fill_mode, args.gdb_xml_descr)
